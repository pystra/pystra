def test_constant_and_dependent_designs_stay_identifiable():
    points = np.random.default_rng(1).normal(size=(50, 2))
    points[:, 1] = points[:, 0]
    surrogate = PCESurrogate(seed=1)
    surrogate.fit(points, np.ones(50) * 3)
    assert len(surrogate.fit_result.indices) == 1
    mean, spread = surrogate.predict(points)
    np.testing.assert_allclose(mean, 3, atol=1e-12)
    assert spread.max() < 1e-12
    surrogate.fit(points, 1 + points[:, 0])
    assert len(surrogate.fit_result.indices) == 2
    np.testing.assert_allclose(
        surrogate.predict(points)[0], 1 + points[:, 0], atol=1e-12
    )


def test_rank_deficient_bootstrap_uses_minimum_norm_and_reports_count():
    points = np.random.default_rng(6).normal(size=(8, 2))
    values = np.exp(points[:, 0]) + points[:, 1]
    surrogate = PCESurrogate(method="ols", degree=2, n_bootstrap=30, seed=3)
    surrogate.fit(points, values)
    result = surrogate.fit_result
    assert result.n_rank_deficient_bootstrap > 0
    # Include every uniform resample, including unidentifiable ones, exactly
    # as UQLab's least-squares bootstrap. No conditioning on full rank.
    basis = _hermite_basis(points, np.asarray(result.indices))
    predictions = []
    rng = np.random.default_rng(3)
    for _ in range(30):
        rows = rng.integers(len(points), size=len(points))
        coefficients = np.linalg.pinv(basis[rows]) @ values[rows]
        predictions.append(basis @ coefficients)
    np.testing.assert_allclose(
        surrogate.predict(points)[1], np.std(predictions, axis=0, ddof=1), rtol=1e-10
    )
